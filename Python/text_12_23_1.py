

# 切片

maps = ['北京', '上海', '广州', '深圳', '杭州', '成都', '武汉', '西安', '重庆', '南京']
print(maps[0:3])  # ['北京', '上海', '广州']

print(maps[2:5])  #

print(maps[1:8:2])  # ['成都', '武汉', '西安']

maps.sort()
print(maps)


